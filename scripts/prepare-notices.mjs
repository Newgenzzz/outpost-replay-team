// Collect notices from the actual Vite/Rollup runtime module graph, offline.
import { build } from 'vite';
import fs from 'node:fs';
import path from 'node:path';

const result = await build({ logLevel: 'silent', build: { write: false } });
const packages = new Map();
for (const chunk of result.output) {
  if (chunk.type !== 'chunk') continue;
  for (const id of Object.keys(chunk.modules)) {
    if (!id.includes('/node_modules/')) continue;
    let dir = path.dirname(id.replace(/^\0/, ''));
    while (dir.includes('/node_modules/')) {
      const manifest = path.join(dir, 'package.json');
      if (fs.existsSync(manifest)) {
        const pkg = JSON.parse(fs.readFileSync(manifest, 'utf8'));
        if (pkg.name && pkg.version) { packages.set(`${pkg.name}@${pkg.version}`, { ...pkg, dir }); break; }
      }
      dir = path.dirname(dir);
    }
  }
}
const sections = ['OUTPOST REPLAY — bundled software notices\nGenerated by node scripts/prepare-notices.mjs from installed packages and the production module graph.\nThese licenses apply to third-party software only. No license for team materials is granted here.\nScientific credits: NASA_SCIENCE.md. Artwork provenance and team license: ATTRIBUTION.md.\nReview embedded upstream components as part of release approval.'];
for (const pkg of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  const files = fs.readdirSync(pkg.dir).filter(f => /^(licen[sc]e|copying|notice|copyright)(\.|$)/i.test(f)).map(f => [f, path.join(pkg.dir, f)]);
  if (pkg.name === '@react-three/fiber') {
    files.push(['@react-three/fiber upstream license', 'licensing/react-three-fiber-LICENSE.txt']);
  }
  if (pkg.name === 'victory-vendor') {
    files.push(['Victory upstream license', 'licensing/Victory-LICENSE.txt']);
    for (const dir of fs.readdirSync(path.join(pkg.dir, 'lib-vendor'))) {
      const file = path.join(pkg.dir, 'lib-vendor', dir, 'LICENSE');
      if (fs.existsSync(file)) files.push([`lib-vendor/${dir}/LICENSE`, file]);
    }
  }
  if (!files.length) throw new Error(`Missing notice for ${pkg.name}; review before release`);
  sections.push(`${pkg.name} ${pkg.version}\nDeclared license: ${pkg.license}\n${files.map(([label, file]) => `${label}\n${fs.readFileSync(file, 'utf8')}`).join('\n')}`);
}
fs.writeFileSync('public/THIRD_PARTY_NOTICES.txt', sections.join('\n\n' + '='.repeat(72) + '\n\n') + '\n');
console.log(`Prepared notices for ${packages.size} bundled packages. Rebuild dist/ before release.`);
